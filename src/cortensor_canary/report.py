"""Human-readable reports: Markdown and a self-contained HTML page."""

from __future__ import annotations

import html
from datetime import datetime, timezone
from pathlib import Path
from typing import Any

from .runner import Run


def _esc(value: Any) -> str:
    return html.escape(str(value if value is not None else ""), quote=True)


def _pct(value: float, digits: int = 1) -> str:
    return f"{value * 100:.{digits}f}%"


def _ms(value: float) -> str:
    return f"{value:.0f} ms"


def _status_icon(status: str) -> str:
    return {"PASS": "✅", "WARN": "⚠️", "FAIL": "❌"}.get(status.upper(), "•")


def _delta_class(value: float) -> str:
    if value > 0:
        return "up"
    if value < 0:
        return "down"
    return "flat"


def render_markdown(baseline: Run, candidate: Run, comparison: dict[str, Any]) -> str:
    b = comparison["baseline"]["metrics"]
    c = comparison["candidate"]["metrics"]
    d = comparison["deltas"]
    lines = [
        f"# Cortensor Canary report — {comparison['status']}",
        "",
        f"Generated {comparison['created_at']} by `cortensor-canary`.",
        "",
        f"**Baseline:** `{baseline.target.name}` · `{baseline.target.model}` · suite `{baseline.suite.name}`  ",
        f"**Candidate:** `{candidate.target.name}` · `{candidate.target.model}` · suite `{candidate.suite.name}`",
        "",
        "## Verdict",
        "",
        "```",
        comparison["verdict_text"],
        "```",
        "",
        "## Metrics",
        "",
        "| Metric | Baseline | Candidate | Delta |",
        "|---|---:|---:|---:|",
        f"| Pass rate | {_pct(b['pass_rate'])} | {_pct(c['pass_rate'])} | {d['pass_rate_pp']:+.1f} pp |",
        f"| Error rate | {_pct(b['error_rate'])} | {_pct(c['error_rate'])} | {d['error_rate_pp']:+.1f} pp |",
        f"| p50 latency | {_ms(b['latency_ms']['p50'])} | {_ms(c['latency_ms']['p50'])} | {d['p50_latency_pct']:+.1f}% |",
        f"| p95 latency | {_ms(b['latency_ms']['p95'])} | {_ms(c['latency_ms']['p95'])} | {d['p95_latency_pct']:+.1f}% |",
        f"| Tokens | {b['tokens']['total']:,} | {c['tokens']['total']:,} | {d['tokens_total_pct']:+.1f}% |",
        f"| Cases | {b['cases']} | {c['cases']} | — |",
        "",
        "## Gates",
        "",
        "| Check | Value | Gate | Status |",
        "|---|---:|---:|---|",
    ]
    for check in comparison["checks"]:
        lines.append(
            f"| {check['name']} | {check['value']:+.1f}{check['unit']} | {check['gate']:+.1f}{check['unit']} "
            f"| {_status_icon(check['status'])} {check['status'].upper()} |"
        )

    lines += ["", "## Cases", "", "| Case | Baseline | Candidate | Detail |", "|---|---|---|---|"]
    base_cases = {case.id: case for case in baseline.cases}
    for case in candidate.cases:
        base = base_cases.get(case.id)
        base_cell = "—" if base is None else ("✅" if base.passed else "❌")
        cand_cell = "✅" if case.passed else ("❌" if not case.error else "💥")
        detail = case.detail if not case.error else f"error: {case.error}"
        lines.append(f"| `{case.id}` | {base_cell} | {cand_cell} | {str(detail)[:120]} |")

    lines += [
        "",
        "---",
        "Generated by [Cortensor Canary](https://github.com/9xj89gzrtw-hue/cortensor-openminion-agent). "
        "Scores are deterministic; no LLM judge is involved.",
        "",
    ]
    return "\n".join(lines)


